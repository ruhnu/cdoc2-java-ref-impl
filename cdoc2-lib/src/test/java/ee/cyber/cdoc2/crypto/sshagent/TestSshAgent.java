package ee.cyber.cdoc2.crypto.sshagent;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.concurrent.TimeUnit;

import org.junit.jupiter.api.Assumptions;


/**
 * Real ssh-agent for tests, started on a socket in a temporary directory. The agent's askpass is /bin/false,
 * so keys added with {@code confirm=true} (ssh-add -c) are always refused.
 */
public final class TestSshAgent implements AutoCloseable {

    private final Path dir;
    private final Path socket;
    private final Process agent;

    private TestSshAgent(Path dir, Path socket, Process agent) {
        this.dir = dir;
        this.socket = socket;
        this.agent = agent;
    }

    /**
     * Start ssh-agent. Test is skipped if ssh-agent or ssh-keygen is not installed.
     * @param dir short directory path (unix socket path is limited to ~108 bytes)
     */
    public static TestSshAgent start(Path dir) throws IOException, InterruptedException {
        Assumptions.assumeTrue(isInstalled("ssh-agent") && isInstalled("ssh-keygen") && isInstalled("ssh-add"),
            "ssh-agent, ssh-add and ssh-keygen required");

        Path socket = dir.resolve("agent.sock");
        ProcessBuilder pb = new ProcessBuilder("ssh-agent", "-D", "-a", socket.toString())
            .redirectErrorStream(true)
            .redirectOutput(ProcessBuilder.Redirect.DISCARD);
        pb.environment().put("SSH_ASKPASS", "/bin/false");
        pb.environment().put("SSH_ASKPASS_REQUIRE", "force");
        pb.environment().remove("DISPLAY");
        Process agent = pb.start();

        for (int i = 0; i < 100 && !Files.exists(socket); i++) {
            Thread.sleep(50);
        }
        if (!Files.exists(socket)) {
            agent.destroyForcibly();
            throw new IllegalStateException("ssh-agent did not create socket " + socket);
        }
        return new TestSshAgent(dir, socket, agent);
    }

    public Path socket() {
        return socket;
    }

    public SshAgentClient client() {
        return new SshAgentClient(socket);
    }

    /** Environment for {@link SshAgentClient#fromEnvironment(Map)} */
    public Map<String, String> env() {
        return Map.of(SshAgentClient.SSH_AUTH_SOCK, socket.toString());
    }

    /**
     * Generate key with ssh-keygen, without adding it to the agent
     * @param name key file name
     * @param type ssh-keygen -t value ("ecdsa", "ed25519", "rsa")
     * @return OpenSSH public key line
     */
    public String generateKey(String name, String type) throws IOException, InterruptedException {
        Path key = dir.resolve(name);
        List<String> cmd = "ecdsa".equals(type)
            ? List.of("ssh-keygen", "-q", "-t", "ecdsa", "-b", "256", "-N", "", "-C", name + "@test", "-f",
                key.toString())
            : List.of("ssh-keygen", "-q", "-t", type, "-N", "", "-C", name + "@test", "-f", key.toString());
        run(cmd, Map.of());
        return Files.readString(dir.resolve(name + ".pub"), StandardCharsets.US_ASCII).strip();
    }

    /** Path of private key generated by {@link #generateKey} */
    public Path keyFile(String name) {
        return dir.resolve(name);
    }

    /**
     * Add generated key to the agent
     * @param name key file name given to {@link #generateKey}
     * @param confirm add with ssh-add -c (every use must be confirmed, always refused here)
     */
    public void addKey(String name, boolean confirm) throws IOException, InterruptedException {
        List<String> cmd = confirm
            ? List.of("ssh-add", "-q", "-c", dir.resolve(name).toString())
            : List.of("ssh-add", "-q", dir.resolve(name).toString());
        run(cmd, env());
    }

    private static void run(List<String> cmd, Map<String, String> env) throws IOException, InterruptedException {
        ProcessBuilder pb = new ProcessBuilder(cmd).redirectErrorStream(true);
        pb.environment().putAll(env);
        Process p = pb.start();
        String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        if (!p.waitFor(30, TimeUnit.SECONDS) || p.exitValue() != 0) {
            throw new IllegalStateException(cmd + " failed: " + out);
        }
    }

    private static boolean isInstalled(String program) {
        try {
            Process p = new ProcessBuilder("sh", "-c", "command -v " + program).start();
            return p.waitFor(10, TimeUnit.SECONDS) && p.exitValue() == 0;
        } catch (IOException | InterruptedException e) {
            return false;
        }
    }

    @Override
    public void close() {
        agent.destroy();
        try {
            agent.waitFor(5, TimeUnit.SECONDS);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
    }
}
